// ─────────────────────────────────────────────────────────────────────────────
// Root Layout
// ─────────────────────────────────────────────────────────────────────────────

// Marks JS as available, so progressive enhancements (the scroll-driven hero) key on it.
const JS_FLAG = "document.documentElement.classList.add('js')";

// Runs before first paint: applies a saved theme choice so there is no flash of the wrong
// theme. With no saved choice the site is light, whatever the system preference. try/catch
// because storage can be blocked.
const THEME_INIT =
  "try{var t=localStorage.getItem('theme');if(t==='light'||t==='dark')document.documentElement.setAttribute('data-theme',t)}catch(e){}";
// Decides, before first paint, whether the opening card shows (see Splash.tsx): home page, no
// hash, motion allowed, and not a crawler (so a render for indexing is never covered). It runs on every load. The timeout un-sticks the page even if React
// never hydrates.
const SPLASH_INIT =
  "try{var d=document.documentElement;if(location.pathname==='/'&&!location.hash&&!matchMedia('(prefers-reduced-motion: reduce)').matches&&!/bot|crawl|spider|slurp|lighthouse|prerender/i.test(navigator.userAgent)){d.classList.add('splash-on');setTimeout(function(){d.classList.remove('splash-on')},3000)}}catch(e){}";

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${display.variable} ${body.variable} ${mono.variable}`}
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_INIT + ';' + JS_FLAG + ';' + SPLASH_INIT }} />
      </head>
      <body>
        <a href="#main" className="skip-link">
          Skip to content
        </a>
        <CursorGlow />
        {children}
        <RevealController />
        <ParallaxController />
        <Magnetic />
        <RegisterFade />
      </body>
    </html>
  );
}
